// ---- Индикатор: разводка v2 (как в led_clock_v2), docs/03-hardware.md ----
// Нельзя: 6–11 (флеш); 34–39 — только вход; 0, 2, 5, 12, 15 — влияют на загрузку.

// Верхний ряд ножек индикатора (10…6) — верхний ряд платы
#define DIGIT1_PIN  32   // D32 -> ножка 10 — анод левой цифры
#define SEG_B_PIN   33   // D33 -> ножка 9
#define SEG_C_PIN   25   // D25 -> ножка 8
#define SEG_E_PIN   26   // D26 -> ножка 7
#define SEG_D_PIN   27   // D27 -> ножка 6

// Нижний ряд ножек индикатора (1…5) — нижний ряд платы
#define SEG_G_PIN   18   // D18 -> ножка 1
#define SEG_DP_PIN  19   // D19 -> ножка 2
#define SEG_A_PIN   21   // D21 -> ножка 3
#define SEG_F_PIN   22   // D22 -> ножка 4
#define DIGIT2_PIN  23   // D23 -> ножка 5 — анод правой цифры

#define DIGIT_ON_LEVEL    HIGH   // HIGH — аноды напрямую; LOW — через PNP
#define SEGMENT_ON_LEVEL  LOW    // общий анод
#define DIGIT_ON_TIME_US  2000
#define SELFTEST_STEP_MS  400

// ---- Датчик температуры: NTC-капля с платы обогревателя ----
// Схема: GPIO14 (HIGH) -> 10 кОм -> GPIO34 -> NTC -> GND
#define NTC_ADC_PIN    34       // вход АЦП1 (34–39 — только вход, подходят идеально)
#define NTC_POWER_PIN  14       // питание делителя; -1 — если делитель от вывода 3V3
#define NTC_R_FIXED    10000.0  // резистор делителя, Ом
#define NTC_R25        10000.0  // сопротивление датчика при 25 °C, Ом
#define NTC_BETA       3950.0   // коэффициент B (замеры: 6,2 кОм подмышкой ~36 °C)
#define NTC_SUPPLY_MV  3300     // напряжение питания делителя, мВ
#define TEMP_OFFSET_C  0.0      // поправка, °C: если сверили с термометром и есть сдвиг
#define TEMP_SAMPLE_MS 100      // период замеров, мс
#define TEMP_LOG_MS    2000     // период вывода в лог, мс
